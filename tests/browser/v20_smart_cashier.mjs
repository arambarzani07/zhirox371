import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {dirname,resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {chromium} from "playwright";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"../..");
const fixture=readFileSync(resolve(root,"tests/browser/qa_supabase_fixture.js"),"utf8");
const origin=process.env.PC_PREVIEW_ORIGIN||"http://127.0.0.1:8765";
const seed='(() => {const q=window.__retailQA;q.products[0].name="تەماتە";q.products[0].base_unit="kg";q.products[0].plu="00001";q.products[0].price_minor=1250;q.stock[0].quantity=2;q.sessions.push({id:"dddddddd-dddd-4ddd-8ddd-dddddddddddd",store_id:q.store.id,cashier_id:q.account.id,opening_cash_minor:100000,opened_at:new Date().toISOString(),status:"open"});})();';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1190,height:850}});
const failures=[];
page.on("pageerror",e=>failures.push(e.message));
await page.route("https://cdn.jsdelivr.net/**",r=>r.fulfill({status:200,contentType:"application/javascript",body:"/* QA only */"}));
await page.addInitScript({content:fixture+seed});
const scan=async code=>{
 await page.locator("#barcode").fill(code);
 await page.locator("#barcode").press("Enter");
};
try{
 await page.goto(origin+"/operations.html?view=cash",{waitUntil:"load"});
 await page.locator("#cash-panel").waitFor({state:"visible"});
 await scan("2700001002451");
 await page.waitForFunction(()=>document.querySelector("#total")?.textContent==="306 IQD");
 assert.equal(await page.locator("#cart-body tr").count(),1);
 await scan("2700001002451");
 assert.match(await page.locator("#scan-msg").innerText(),/پێشتر سکان کراوە/);
 assert.equal(await page.locator("#total").innerText(),"306 IQD");
 await scan("2700001003809");
 await page.waitForFunction(()=>document.querySelector("#total")?.textContent==="781 IQD");
 assert.equal(await page.locator("#cart-body tr").count(),2);
 const weights=await page.locator("#cart-body tr .basket-qty-value").allTextContents();
 assert.deepEqual(weights,["0.245","0.380"]);
 assert.equal(await page.locator("#cart-body tr [data-delta='1']").first().isDisabled(),true);
 await page.locator("#cart-body [data-remove-line='0']").click();
 assert.equal(await page.locator("#total").innerText(),"475 IQD");
 assert.equal(await page.locator("#cart-body tr").count(),1);
 await page.evaluate(()=>{window.__retailQA.products[0].price_minor=1400;window.__retailQA.indexVersion++;});
 await page.locator("#cash").fill("475");
 await page.locator("#finish-sale").click();
 await page.waitForFunction(()=>document.querySelector("#checkout-msg")?.textContent?.includes("تۆمار نەکرا"));
 assert.equal(await page.evaluate(()=>window.__retailQA.sales.length),0,"price drift must not post a sale");
 assert.equal(await page.locator("#cart-body tr").count(),1,"outdated basket must remain to review");
 assert.match(await page.locator("#cart-body .basket-stale").innerText(),/گۆڕاوە/);
 await page.locator("#cart-body [data-remove-line='0']").click();
 assert.equal(await page.locator("#total").innerText(),"0 IQD");
 assert.deepEqual(failures,[]);
 console.log("PASS V20: different weighed packs, duplicate scan protection, removal, live price drift blocks checkout");
}finally{await browser.close()}
